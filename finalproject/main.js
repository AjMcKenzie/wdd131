const currentPage = window.location.pathname.split("/").pop();
const content = document.getElementById("content");
const navLinks = document.querySelectorAll("nav a");

const next = document.getElementById("next");
const prev = document.getElementById("prev");
const random = document.getElementById("random");

let currentChapterIndex = 0;
let currentBookIndex = 0;
let showingFront = true;

let menuButton = document.getElementsByClassName("menu-btn")[0];
menuButton.addEventListener("click", handleMenuButtonClick);

let card = document.getElementById("card");
let contentSection = document.getElementById("content");

const chapterButtons = document.querySelectorAll("#numbers button");

function getChapterCount() {
    if (currentPage === "chapters.html") {
        return chapterPegs.length;
    } else {
        return chapterData.length;
    }
}

let bookButtons = document.querySelectorAll("#BOMbooks button");

function getBookCount() {
    if (currentPage === "books.html") {
        return bookPegs.length;
    } else {
        return bookPegs.length;
    }
}


if (navLinks.length > 0) {
    navLinks.forEach((link) => {
        if (link.getAttribute("href") === currentPage) {
            link.classList.add("active");
        }
    });
}

function renderCard() {
    if (currentPage === "chapters.html") {
        const row = chapterPegs[currentChapterIndex];
        const frontText = `${row.chapter}`;
        const backText = row.peg;
        if (showingFront) {
            content.textContent = frontText;
        } else {
            content.textContent = backText;
        }
    } else if (currentPage === "books.html") {
        const row = bookPegs[currentBookIndex];
        const frontText = `${row.book}`;
        const backText = row.peg;
        if (showingFront) {
            content.textContent = frontText;
        } else {
            content.textContent = backText;
        }
    } else if (currentPage === "learn.html") {
        const row = chapterData[currentChapterIndex];
        const frontText = `${row.story}`;
        const backText = `${row.doctrine} \n(${row.book} ${row.chapter}${row.ref})`;
        if (showingFront) {
            content.textContent = frontText;
        } else {
            content.textContent = backText;
        }
    }else if (currentPage === "test.html") {
        const row = chapterData[currentChapterIndex];
        const frontText = `${row.doctrine}`;
        const backText = `${row.book} ${row.chapter}`;
        if (showingFront) {
            content.textContent = frontText;
        } else {
            content.textContent = backText;
        }
    }
}

function randomize(){
    currentChapterIndex = Math.floor(Math.random() * getChapterCount());
    currentBookIndex = Math.floor(Math.random() * bookPegs.length);
    showingFront = true;
    renderCard();
}

function handleMenuButtonClick(event) {
    let nav = document.querySelector("nav");
    nav.classList.toggle("hide");
    menuButton.classList.toggle("change");
}

if(currentPage !== "index.html") {

    card.addEventListener("click", () => {
        showingFront = !showingFront;
        card.classList.toggle("flipped");
        contentSection.classList.toggle("unflipped");
    
        renderCard();
    });
    
    next.addEventListener("click", () => {
        if (currentPage === "test.html") {
            randomize();
        }else{
            currentChapterIndex = (currentChapterIndex + 1) % getChapterCount();
            currentBookIndex = (currentBookIndex + 1) % bookPegs.length;
            showingFront = true;
            renderCard();
        }

    });
    
    if (prev) {
        prev.addEventListener("click", () => {
            currentChapterIndex = (currentChapterIndex - 1 + getChapterCount()) % getChapterCount();
            currentBookIndex = (currentBookIndex - 1 + bookPegs.length) % bookPegs.length;
            showingFront = true;
            renderCard();
        });
    }
    
    if (random) {
        random.addEventListener("click", () => {
            randomize();
        });
    }

    chapterButtons.forEach((button, index) => {
        button.addEventListener("click", () => {
            currentChapterIndex = index;
            showingFront = true;
            card.classList.remove("flipped");
            contentSection.classList.remove("unflipped");
            renderCard();
        });
    });

    bookButtons.forEach((button, index) => {
        button.addEventListener("click", () => {
            currentBookIndex = index;
            showingFront = true;
            card.classList.remove("flipped");
            contentSection.classList.remove("unflipped");
            renderCard();
        });
    });

    if (currentPage === "test.html") {
        randomize();
    }
    
    renderCard();
}



